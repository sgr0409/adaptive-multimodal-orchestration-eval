"""Generates the synthetic equipment-maintenance-triage benchmark.

Every scenario has three modalities -- a text maintenance ticket, a
synthetic gauge image (procedurally drawn, not sourced from any real
equipment), and a telemetry time series (temperature/vibration/pressure) --
plus a ground-truth severity label in {normal, warning, critical}, which
maps 1:1 to a recommended action {monitor, schedule_maintenance,
immediate_shutdown}.

Critically, each scenario has a random *number* (0, 1, or 2) of
deliberately "degraded" modalities: their content is made uninformative
about the true label (a vague ticket, a blurred/ambiguous gauge, or
noise-dominated telemetry), while any remaining modalities stay clearly
correlated with the true label. This is a disclosed, deliberate
construction choice, not an incidental property of the data.

An earlier version of this dataset only ever degraded at most one
modality at a time. That made the confidence-weighted vs. equal-weight
fusion comparison uninformative: with two clean modalities always
outvoting one degraded one, both fusion strategies reached 100% test
accuracy regardless of weighting -- a ceiling effect, not evidence that
confidence-awareness does anything. Two-degraded-modality scenarios are
the condition that actually stresses the mechanism: equal-weight fusion
gets outvoted by the two unreliable modalities, while confidence-weighted
fusion can still recover the correct answer if the one remaining clean
modality's confidence is high enough relative to the two degraded ones'.
Distribution: 20% zero degraded modalities, 30% exactly one, 50% exactly
two (weighted toward the condition that actually differentiates the two
fusion strategies, the same way the paper's own dataset design should be
judged on whether it can surface a real effect, not just look busy).

Everything is generated by this script from a fixed seed (42); nothing
here is sourced from real equipment, real maintenance records, or any
other real-world data.
"""
import json
import random
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

SEED = 42
DATA_DIR = Path(__file__).parent
IMG_DIR = DATA_DIR / "images"
N_PER_CLASS = 500
LABELS = ["normal", "warning", "critical"]
ACTION_OF = {
    "normal": "monitor",
    "warning": "schedule_maintenance",
    "critical": "immediate_shutdown",
}

TEXT_TEMPLATES = {
    "normal": [
        "Routine inspection completed, all readings nominal.",
        "Equipment operating within normal parameters during shift check.",
        "No abnormalities observed. Standard operating condition confirmed.",
        "Scheduled check-in: unit running smoothly, no operator concerns.",
        "Daily walkthrough complete, everything within spec.",
    ],
    "warning": [
        "Operator noted unusual vibration during operation, recommend inspection.",
        "Slight temperature increase observed over the last shift, monitoring recommended.",
        "Minor irregular noise reported during startup, may need a closer look.",
        "Pressure readings trending slightly high; worth scheduling a check.",
        "Intermittent rattling noticed under load, not yet urgent but flagged.",
    ],
    "critical": [
        "Loud grinding noise and visible smoke reported near the housing.",
        "Emergency: equipment showing signs of imminent bearing failure.",
        "Severe fluid leak detected at the base, immediate attention required.",
        "Unit tripped on overtemperature alarm, operator evacuated the area.",
        "Visible sparking and burning smell reported, shut down requested.",
    ],
    "degraded": [
        "Ticket submitted for equipment review.",
        "Please check equipment when convenient.",
        "Routine ticket logged per weekly process.",
        "Operator submitted a general status update.",
        "Ticket opened for equipment on the maintenance queue.",
    ],
}

# (severity_low_deg, severity_high_deg) needle angle range in degrees,
# measured from the left end of the gauge arc (0) to the right end (180).
# The arc is drawn as a monotonic green[0,60) -> yellow[60,120) -> red[120,180]
# gradient, so these ranges sit safely inside their zone with a 10-degree
# margin from each boundary.
GAUGE_ZONES = {"normal": (10, 50), "warning": (70, 110), "critical": (130, 170)}

TELEMETRY_PROFILES = {
    # (mean, std) per channel: temperature (C), vibration (g), pressure (kPa)
    "normal": {"temperature": (60, 3), "vibration": (0.20, 0.05), "pressure": (100, 5)},
    "warning": {"temperature": (75, 4), "vibration": (0.50, 0.08), "pressure": (115, 7)},
    "critical": {"temperature": (95, 5), "vibration": (0.90, 0.10), "pressure": (135, 10)},
}
N_TIMESTEPS = 20


def draw_gauge(rng, angle_deg, degraded):
    """Draws a 128x128 semicircular gauge with green/yellow/red zones and a
    needle at angle_deg (0=left/normal end, 180=right/critical end). If
    degraded, the needle is drawn at an ambiguous boundary angle and the
    whole image is heavily blurred/noised so the zone is not recoverable."""
    size = 128
    img = Image.new("RGB", (size, size), "white")
    draw = ImageDraw.Draw(img)
    cx, cy, r = size // 2, size - 10, size // 2 - 10

    # Monotonic gradient matching angle_deg 0->180 (normal->critical):
    # green[180,240) -> yellow[240,300) -> red[300,360) in PIL arc degrees.
    draw.arc([cx - r, cy - r, cx + r, cy + r], 180, 240, fill=(40, 160, 40), width=14)
    draw.arc([cx - r, cy - r, cx + r, cy + r], 240, 300, fill=(220, 180, 20), width=14)
    draw.arc([cx - r, cy - r, cx + r, cy + r], 300, 360, fill=(200, 40, 40), width=14)

    import math
    theta = math.radians(180 + angle_deg)
    nx = cx + (r - 8) * math.cos(theta)
    ny = cy + (r - 8) * math.sin(theta)
    draw.line([cx, cy, nx, ny], fill=(20, 20, 20), width=4)
    draw.ellipse([cx - 5, cy - 5, cx + 5, cy + 5], fill=(20, 20, 20))

    if degraded:
        img = img.filter(ImageFilter.GaussianBlur(radius=6))
        noise = Image.effect_noise((size, size), 60).convert("RGB")
        img = Image.blend(img, noise, alpha=0.35)
    return img


def gen_telemetry(rng, label, degraded):
    series = {}
    for channel in TELEMETRY_PROFILES["normal"]:
        if degraded:
            # Wide-range uniform noise spanning across all three severity
            # profiles for this channel (not centered on any single one).
            # This is what makes it genuinely *ambiguous* rather than
            # confidently wrong: an earlier version of this function drew
            # degraded readings from one randomly-picked profile's clean
            # distribution, which produced a confident (just possibly
            # incorrect) reading rather than an uncertain one -- a
            # feature-based classifier trained on tight per-class clusters
            # sees this wide-spread noise as visibly unlike any training
            # class (its variance alone is far outside what any single
            # class's std produces) and should respond with lower
            # confidence across the board, which is the actual property
            # confidence-aware fusion needs to detect.
            all_means = [TELEMETRY_PROFILES[l][channel][0] for l in LABELS]
            all_stds = [TELEMETRY_PROFILES[l][channel][1] for l in LABELS]
            lo = min(all_means) - 3 * all_stds[all_means.index(min(all_means))]
            hi = max(all_means) + 3 * all_stds[all_means.index(max(all_means))]
            series[channel] = [round(rng.uniform(lo, hi), 3) for _ in range(N_TIMESTEPS)]
        else:
            mean, std = TELEMETRY_PROFILES[label][channel]
            series[channel] = [round(rng.gauss(mean, std), 3) for _ in range(N_TIMESTEPS)]
    return series


MODALITY_NAMES = ["text", "image", "telemetry"]


def main():
    rng = random.Random(SEED)
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    records = []
    idx = 0
    for label in LABELS:
        for _ in range(N_PER_CLASS):
            n_degraded = rng.choices([0, 1, 2], weights=[0.2, 0.3, 0.5])[0]
            degraded_modalities = rng.sample(MODALITY_NAMES, n_degraded)

            text = rng.choice(TEXT_TEMPLATES["degraded" if "text" in degraded_modalities else label])

            if "image" in degraded_modalities:
                # Uninformativeness comes from the blur/noise corruption
                # below, not needle placement -- a fixed "boundary" angle
                # would still be legible in a clean monotonic gauge, so we
                # randomize the angle across the full range instead.
                angle = rng.uniform(0, 180)
            else:
                lo, hi = GAUGE_ZONES[label]
                angle = rng.uniform(lo, hi)
            img = draw_gauge(rng, angle, degraded=("image" in degraded_modalities))
            img_path = IMG_DIR / f"scenario_{idx:04d}.png"
            img.save(img_path)

            telemetry = gen_telemetry(rng, label, degraded=("telemetry" in degraded_modalities))

            records.append({
                "id": idx,
                "text": text,
                "image_path": str(img_path.relative_to(DATA_DIR)),
                "telemetry": telemetry,
                "label": label,
                "action": ACTION_OF[label],
                "degraded_modalities": degraded_modalities,  # ground truth, not fed to the model
            })
            idx += 1

    rng.shuffle(records)
    for i, r in enumerate(records):
        r["id"] = i

    out_path = DATA_DIR / "scenarios.jsonl"
    with open(out_path, "w") as f:
        for r in records:
            f.write(json.dumps(r) + "\n")

    from collections import Counter
    count_dist = Counter(len(r["degraded_modalities"]) for r in records)
    print(f"Wrote {len(records)} scenarios to {out_path}")
    print(f"  degraded-modality-count distribution: "
          f"0={count_dist[0]}, 1={count_dist[1]}, 2={count_dist[2]}")
    for m in MODALITY_NAMES:
        n = sum(1 for r in records if m in r["degraded_modalities"])
        print(f"  {m} degraded in {n} scenarios")


if __name__ == "__main__":
    main()
