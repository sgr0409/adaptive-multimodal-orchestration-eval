"""Two learned fusion baselines, added because equal-weight fusion alone is
a weak comparison point for confidence-weighted fusion (framework/fusion.py):
it establishes that confidence weighting beats *no* weighting, not that it
is competitive with a fusion mechanism that learns how to combine modalities
from data.

Both are trained on out-of-fold per-modality predictions generated by
k-fold cross-validation within the train split (standard stacked-
generalization practice), so the meta-learner never sees a prediction from
a base scorer that was fit on that same example. The base scorers deployed
at test time are still fit on the full train split, identical to every
other fusion method in this paper's evaluation -- isolating the fusion
mechanism as the thing under test, not the base scorers or a train-size
advantage.

StackingFusion: a logistic-regression meta-classifier over the
concatenated per-modality probability distributions (3 classes x 3
modalities = 9 features) -- the standard "late fusion via stacking"
baseline in the multimodal-fusion literature.

LearnedGatingFusion: a small MLP that maps the three modalities' own
confidence scores to a softmax gating weight per modality, trained
end-to-end via the weighted-sum fused distribution's cross-entropy loss
against the true label, rather than hand-specified as confidence^p. This
tests whether a learned weighting function of confidence beats this
paper's swept-but-fixed power=3 rule (Eq.~\ref{eq:fusion}) -- a form of
learned attention over modality confidence, not a fixed formula."""
import numpy as np
import torch
import torch.nn as nn
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler


def _labels_of(modality_results):
    return sorted(modality_results[0]["probs"].keys())


def _stack_features(modality_results, labels):
    return np.array([r["probs"][l] for r in modality_results for l in labels])


def _confidence_features(modality_results):
    return np.array([r["confidence"] for r in modality_results])


class StackingFusion:
    def __init__(self):
        self.clf = make_pipeline(StandardScaler(), LogisticRegression(max_iter=1000, random_state=42))
        self.labels_ = None
        self._fitted = False

    def fit(self, oof_modality_results_list, y):
        self.labels_ = _labels_of(oof_modality_results_list[0])
        X = np.array([_stack_features(mr, self.labels_) for mr in oof_modality_results_list])
        self.clf.fit(X, y)
        self._fitted = True

    def predict(self, modality_results):
        assert self._fitted, "StackingFusion.fit() must be called before predict()"
        x = _stack_features(modality_results, self.labels_).reshape(1, -1)
        probs = self.clf.predict_proba(x)[0]
        classes = list(self.clf.classes_)
        best_idx = int(np.argmax(probs))
        return {
            "modality": "stacking_fusion",
            "label": classes[best_idx],
            "confidence": float(probs[best_idx]),
            "probs": {c: float(p) for c, p in zip(classes, probs)},
        }


class _GateNet(nn.Module):
    def __init__(self, n_modalities=3, hidden=8):
        super().__init__()
        self.net = nn.Sequential(nn.Linear(n_modalities, hidden), nn.ReLU(), nn.Linear(hidden, n_modalities))

    def forward(self, conf):
        return torch.softmax(self.net(conf), dim=-1)


class LearnedGatingFusion:
    def __init__(self, epochs=300, lr=0.01, seed=42):
        self.epochs = epochs
        self.lr = lr
        self.seed = seed
        self.labels_ = None
        self.model = None
        self._fitted = False

    def fit(self, oof_modality_results_list, y):
        torch.manual_seed(self.seed)
        self.labels_ = _labels_of(oof_modality_results_list[0])
        label_to_idx = {l: i for i, l in enumerate(self.labels_)}

        conf = torch.tensor(np.array([_confidence_features(mr) for mr in oof_modality_results_list]),
                             dtype=torch.float32)
        probs = torch.tensor(np.array([[[r["probs"][l] for l in self.labels_] for r in mr]
                                        for mr in oof_modality_results_list]), dtype=torch.float32)
        y_idx = torch.tensor([label_to_idx[l] for l in y], dtype=torch.long)

        self.model = _GateNet(n_modalities=conf.shape[1])
        opt = torch.optim.Adam(self.model.parameters(), lr=self.lr)
        loss_fn = nn.NLLLoss()
        for _ in range(self.epochs):
            opt.zero_grad()
            weights = self.model(conf)
            fused = torch.einsum("nm,nmc->nc", weights, probs)
            fused = torch.clamp(fused, min=1e-8)
            loss = loss_fn(torch.log(fused), y_idx)
            loss.backward()
            opt.step()
        self._fitted = True

    def predict(self, modality_results):
        assert self._fitted, "LearnedGatingFusion.fit() must be called before predict()"
        conf = torch.tensor(np.array([_confidence_features(modality_results)]), dtype=torch.float32)
        probs = torch.tensor(np.array([[[r["probs"][l] for l in self.labels_] for r in modality_results]]),
                              dtype=torch.float32)
        with torch.no_grad():
            weights = self.model(conf)
            fused = torch.einsum("nm,nmc->nc", weights, probs)[0].numpy()
        best_idx = int(np.argmax(fused))
        return {
            "modality": "learned_gating_fusion",
            "label": self.labels_[best_idx],
            "confidence": float(fused[best_idx]),
            "probs": {l: float(p) for l, p in zip(self.labels_, fused)},
        }
